"""Иерархия пользовательских исключений для конвертера температур.
Все исключения наследуются от ConverterError, чтобы в CLI можно было
перехватывать их одним блоком `except ConverterError`, сохраняя при этом
возможность обрабатывать конкретные типы по отдельности.
"""

from __future__ import annotations


class ConverterError(Exception):
    """Базовый класс для всех ошибок конвертера температур."""


class InvalidInputError(ConverterError):
    """Ошибка некорректного пользовательского ввода.
    Поднимается, если строку не удалось преобразовать в число
    (например: "abc", пустая строка, "NaN", "inf"),
    либо если номер пункта меню вне допустимого диапазона.
    """


class BelowAbsoluteZeroError(ConverterError):
    """Значение температуры ниже абсолютного нуля.
    Сообщение строится в тех же единицах, в которых пользователь вводил
    значение, — так пользователю понятнее.
    Args:
        value: введённое пользователем значение (в исходной шкале).
        scale_code: короткий код шкалы ("C", "F", "K") для сообщения.
        min_allowed: минимально допустимое значение в этой же шкале
            (оно же — абсолютный ноль в этой шкале).
    """

    def __init__(self, value: float, scale_code: str, min_allowed: float) -> None:
        self.value = value
        self.scale_code = scale_code
        self.min_allowed = min_allowed
        super().__init__(
            f"Значение {value:.2f} {scale_code} ниже абсолютного нуля "
            f"(минимум для этой шкалы: {min_allowed:.2f} {scale_code})."
        )


class HistoryError(ConverterError):
    """Ошибка работы с файлом истории.
    Поднимается при проблемах ввода-вывода: файл недоступен,
    нет прав на запись, повреждена структура CSV и т.п.
    """